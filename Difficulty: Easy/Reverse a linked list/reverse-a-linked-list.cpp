class Solution {
  public:
    Node* reverseList(Node* head) {
        Node *curr=head,*prev=NULL,*next=NULL;
        while(curr!=NULL){
            next=curr->next;
            curr->next=prev;
            prev=curr;
            curr=next;
        }
        return prev;
    }
};